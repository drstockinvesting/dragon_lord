/* Inlines a PNG into index.html as the parallax backdrop.
 *
 *     node tools/inline-backdrop.mjs assets/backdrop.png
 *
 * The game reads the inlined copy, never the file on disk -- that is what
 * keeps "one HTML file, double-click to play" true. assets/backdrop.png is
 * the editable master; this is the build step that ships it.
 *
 * Replacing the art with a generated image is exactly this: drop the PNG at
 * assets/backdrop.png and run this. No code changes. See docs/AI-ASSETS.md
 * for the prompt and the constraints any replacement must satisfy.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const BUDGET_KB = 150;
const BEGIN = '/* ==== BACKDROP:BEGIN';
const END   = '/* ==== BACKDROP:END ==== */';

const pngPath = resolve(process.argv[2] || 'assets/backdrop.png');
const htmlPath = resolve(process.argv[3] || 'index.html');

const png = readFileSync(pngPath);
if (png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a'){
  console.error(`error: ${pngPath} is not a PNG.`);
  process.exit(1);
}
const kb = png.length / 1024;

let html = readFileSync(htmlPath, 'utf8');
const i = html.indexOf(BEGIN);
const j = html.indexOf(END);
if (i < 0 || j < 0 || j < i){
  console.error(`error: could not find the BACKDROP:BEGIN/END markers in ${htmlPath}.`);
  process.exit(1);
}

const block =
  `${BEGIN} (generated by tools/inline-backdrop.mjs -- do not hand-edit) ==== */\n` +
  `const BACKDROP_PNG = 'data:image/png;base64,${png.toString('base64')}';\n` +
  END;

const before = html.length;
html = html.slice(0, i) + block + html.slice(j + END.length);
writeFileSync(htmlPath, html);

console.log(`inlined ${pngPath}`);
console.log(`  png    ${kb.toFixed(1)}KB`);
console.log(`  html   ${(before/1024).toFixed(1)}KB -> ${(html.length/1024).toFixed(1)}KB`);
if (kb > BUDGET_KB){
  console.warn(`\nwarning: ${kb.toFixed(1)}KB is over the ${BUDGET_KB}KB budget.`);
  console.warn('The backdrop is a dim silhouette behind gameplay -- it does not need');
  console.warn('detail. Try fewer colours, a lower resolution, or more pure black.');
}
